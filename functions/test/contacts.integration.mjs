import test from 'node:test';
import assert from 'node:assert/strict';
import {initializeApp} from 'firebase-admin/app';
import {getFirestore,Timestamp} from 'firebase-admin/firestore';
import {createContactsPerformance} from '../contacts-performance.js';
if(process.env.FIRESTORE_EMULATOR_HOST!=='127.0.0.1:8185')throw new Error('Local emulator required');
initializeApp({projectId:'demo-royal-clean'},'contacts-tests');
const db=getFirestore((await import('firebase-admin/app')).getApp('contacts-tests'));
const fakeAuth={getUser:async uid=>({uid,email:'admin-contact@example.test',disabled:false,metadata:{creationTime:'2026-09-01T12:00:00.000Z'}})};
test('Server history is idempotent, retains deleted registrations and never copies personal data',async()=>{
 const service=createContactsPerformance({db,auth:fakeAuth,authenticated:async()=>({uid:'tester'}),requireAdmin:async()=>{},rateLimit:async()=>{}});
 const createdAt=Timestamp.fromMillis(Date.now()-30000);
 const data={createdAt,active:true,email:'not-copied@example.test',name:'Not copied'};
 const doc={data:()=>data},none={data:()=>undefined};
 await service.userWritten({params:{uid:'contacts-test-user'},data:{before:none,after:doc},time:new Date().toISOString()});
 const deletion={params:{uid:'contacts-test-user'},data:{before:doc,after:none},time:new Date().toISOString()};
 await service.userWritten(deletion);await service.userWritten(deletion);
 const docs=await db.collection('app_contact_profiles').get();
 const item=docs.docs.find(d=>d.data().createdAt===createdAt.toMillis()).data();
 assert.ok(item.deletedAt);assert.equal(item.email,undefined);assert.equal(item.name,undefined);
 const result=await service.overview({data:{period:'daily'}});
 assert.equal(result.source,'royal-clean');assert.equal(result.bins.at(-1).registered,1);assert.equal(result.bins.at(-1).deleted,1);
});
test('Overview rejects non-admin before querying; heartbeat cannot forge another user presence',async()=>{
 const denied=createContactsPerformance({db,auth:fakeAuth,authenticated:async()=>({uid:'tester'}),requireAdmin:async()=>{throw new Error('denied');},rateLimit:async()=>{}});
 await assert.rejects(()=>denied.overview({data:{period:'daily'}}),/denied/);
 await db.doc('users/heartbeat-test').set({createdAt:Timestamp.now(),active:true});
 const service=createContactsPerformance({db,auth:fakeAuth,authenticated:async()=>({uid:'heartbeat-test'}),requireAdmin:async()=>{},rateLimit:async()=>{}});
 assert.equal((await service.heartbeat({data:{session:'invalid'}})).accepted,false);
 assert.equal((await service.heartbeat({data:{session:'1234567890abcdef',foreground:true,uid:'someone-else'}})).accepted,true);
 const docs=await db.collection('app_contact_presence').get();assert.equal(docs.size,1);
 const result=await service.overview({data:{period:'daily'}});assert.equal(result.bins.at(-1).online,1);
 const removed=await db.doc('users/heartbeat-test').get();
 await db.doc('users/heartbeat-test').delete();
 await service.userWritten({params:{uid:'heartbeat-test'},data:{before:removed,after:{data:()=>null}},time:new Date().toISOString()});
});
test('Admin accounts have real presence and the same account is never counted twice',async()=>{
 const uid='admin-contact-test',account=await fakeAuth.getUser(uid);
 const service=createContactsPerformance({db,auth:fakeAuth,authenticated:async()=>account,requireAdmin:async()=>{},rateLimit:async()=>{}});
 const data={eAdministrador:true,ativo:true,email:account.email};
 await db.doc(`admin/${uid}`).set(data);
 await service.adminWritten({params:{uid},data:{before:{data:()=>null},after:{data:()=>data}},time:new Date().toISOString()});
 assert.equal((await service.heartbeat({data:{session:'admin123456789012',foreground:true}})).accepted,true);
 await db.doc(`users/${uid}`).set({createdAt:Timestamp.now(),active:true});
 await service.userWritten({params:{uid},data:{before:{data:()=>null},after:{data:()=>({createdAt:Timestamp.now(),active:true})}},time:new Date().toISOString()});
 const result=await service.overview({data:{period:'monthly'}});
 assert.equal(result.bins.at(-1).online,1);
 assert.equal(result.bins.at(-1).activityClose,1);
 assert.ok(result.bins.at(-1).activityHigh>=1);
 const candles=await db.collection('app_contact_activity').get();
 assert.equal(candles.size,1);assert.ok(candles.docs[0].data().observations>=3);
 await service.snapshot();
 const after=await db.collection('app_contact_activity').get();
 assert.equal(after.size,1);assert.ok(after.docs[0].data().observations>candles.docs[0].data().observations);
 assert.equal(result.bins.at(-2).registered,1);
});
